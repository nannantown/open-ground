const DEG = { 大: 3, 中: 2, 小: 1 }
const FREQ = { 毎日: 3, 週に数回: 2, たまに: 1 }
export const priority = (s) => {
  const n = DEG[s.deg] * FREQ[s.freq]
  return n >= 6 ? '高' : n >= 3 ? '中' : '低'
}
export const iosCell = (s) => (s.ios === '' ? 'Macだけ' : s.ios === '新' ? '共通（iPhone の一覧に無い）' : `共通 ${s.ios}`)

